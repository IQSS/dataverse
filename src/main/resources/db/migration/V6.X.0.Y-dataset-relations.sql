CREATE TABLE IF NOT EXISTS datasetrelationtype (
                                                   id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                                   name VARCHAR(255) NOT NULL,
                                                   displayname VARCHAR(255) NOT NULL,
                                                   description VARCHAR(255),
                                                   isdefault BOOLEAN NOT NULL DEFAULT FALSE,
                                                   inverse_id BIGINT,
                                                   UNIQUE (name),
                                                   UNIQUE (displayname),
                                                   UNIQUE (inverse_id),
                                                   CONSTRAINT fk_datasetrelationtype_inverse_id FOREIGN KEY (inverse_id) REFERENCES datasetrelationtype(id)
);

CREATE TABLE IF NOT EXISTS datasetrelation (
                                              id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                              dataset_id BIGINT NOT NULL,
                                              definitionpoint_id BIGINT NOT NULL,
                                              relation_source VARCHAR(31),
                                              relateddataset_id BIGINT,
                                              relationtype_id BIGINT NOT NULL,
                                              externalidentifier VARCHAR(512),
                                              identifierscheme VARCHAR(255),
                                              datasettype VARCHAR(255),
                                              CONSTRAINT datasetrelation_internal_unique UNIQUE (dataset_id, relateddataset_id, relationtype_id, definitionpoint_id),
                                              CONSTRAINT datasetrelation_external_unique UNIQUE (dataset_id, externalidentifier, relationtype_id, definitionpoint_id),
                                              CONSTRAINT fk_datasetrelation_dataset_id FOREIGN KEY (dataset_id) REFERENCES dvobject(id),
                                              CONSTRAINT fk_datasetrelation_definitionpoint_id FOREIGN KEY (definitionpoint_id) REFERENCES datasetversion(id),
                                              CONSTRAINT fk_datasetrelation_relateddataset_id FOREIGN KEY (relateddataset_id) REFERENCES dvobject(id),
                                              CONSTRAINT fk_datasetrelation_relationtype_id FOREIGN KEY (relationtype_id) REFERENCES datasetrelationtype(id)
);

CREATE INDEX IF NOT EXISTS index_datasetrelation_dataset ON datasetrelation (dataset_id);
CREATE INDEX IF NOT EXISTS index_datasetrelation_relateddataset ON datasetrelation (relateddataset_id);
CREATE INDEX IF NOT EXISTS index_datasetrelation_definitionpoint ON datasetrelation (definitionpoint_id);
CREATE INDEX IF NOT EXISTS index_datasetrelation_relateddataset_definitionpoint ON datasetrelation (relateddataset_id, definitionpoint_id);
CREATE UNIQUE INDEX IF NOT EXISTS datasetrelationtype_one_default ON datasetrelationtype (isdefault) WHERE isdefault = TRUE;

-- EditDatasetRelations is permission bit 17 (65536). Existing built-in roles
-- that can edit datasets should also be able to edit dataset relations.
UPDATE dataverserole
SET permissionbits = permissionbits | 65536
WHERE owner_id IS NULL AND (permissionbits & 64) != 0;
